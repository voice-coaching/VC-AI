"""Loop A's generator side: CosyVoice2 candidates as ``ReferenceExemplar`` records.

The paper's Loop A produces several renderings of the same sentence so the learner
hears a *range* rather than one voice. This adapter is the step that turns a
synthesis call into an exemplar the rest of the system will accept, and most of its
work is refusing to produce one when the accompanying facts are absent.

A ``ReferenceExemplar`` requires ``license_spdx``, ``rights_basis`` and — for
synthetic audio — a learner-facing ``disclosure``. Those are constructor arguments
here with no defaults, so an exemplar cannot come into existence without them. That
is the point: the audio is playable to a learner, and playing speech whose rights and
synthetic status are unstated is the failure this type was designed to prevent.
"""

from __future__ import annotations

from dataclasses import dataclass
import hashlib
import json
import os
from pathlib import Path
import subprocess
from typing import Any, Mapping

from ..domain import ReferenceExemplar

WORKER_PROTOCOL_VERSION = "voice_coach.cosyvoice_reference_worker.v1"
DEFAULT_WORKER_RELATIVE = Path("scripts/cosyvoice_reference_worker.py")
DEFAULT_INTERPRETER_RELATIVE = Path(".venv-paper-cosyvoice/bin/python")
DEFAULT_VENDOR_RELATIVE = Path("vendor/CosyVoice-074ca6dc")
#: CPU synthesis runs at roughly 12x real time, so a sentence needs minutes.
DEFAULT_TIMEOUT_SECONDS = 1800.0
GENERATOR_ID = "cosyvoice2-0.5b"
VENDOR_REVISION = "074ca6dc9e80a2f424f1f74b48bdd7d3fea531cc"
MODEL_REVISION = "eec1ae6c79877dbd9379285cf8789c9e0879293d"
SPEED_BUCKETS: dict[str, float] = {"slow": 0.8, "neutral": 1.0, "fast": 1.2}
#: The worker inherits nothing it was not given. The thread-count keys are here
#: because the bridge reloads the model per cell, so a bank is generated by many
#: workers at once; without them each one claims every core and they spend their
#: time contending rather than synthesising. They cannot change what is produced,
#: only how many cores produce it.
_ALLOWED_ENVIRONMENT_KEYS = (
    "LANG",
    "LC_ALL",
    "MKL_NUM_THREADS",
    "OMP_NUM_THREADS",
    "PATH",
    "TMPDIR",
)


class ReferenceGeneratorError(ValueError):
    """Raised when synthesis or its declared rights break the contract."""


@dataclass(frozen=True, slots=True)
class VoicePrompt:
    """The prompt voice a candidate is conditioned on, with its rights basis.

    CosyVoice2-0.5B ships no speakers, so every rendering is conditioned on some
    voice. Naming that voice and its basis is therefore not optional metadata — it
    is the difference between a licensed reference and an unattributed voice clone.
    """

    prompt_id: str
    audio_path: Path
    license_spdx: str
    rights_basis: str
    speaker_axis: str
    #: What the prompt recording says. Required, because the worker synthesises
    #: zero-shot: without the transcript the model has no anchor for where the prompt
    #: ended, and measured on the R00 sentences it then overran them by 4-6x.
    prompt_text: str

    def __post_init__(self) -> None:
        for name in (
            "prompt_id",
            "license_spdx",
            "rights_basis",
            "speaker_axis",
            "prompt_text",
        ):
            if not getattr(self, name):
                raise ReferenceGeneratorError(f"{name} must be a non-empty string")
        if not self.audio_path.is_file():
            raise ReferenceGeneratorError("prompt audio is unavailable")


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def content_addressed_name(*, prompt_id: str, text: str, prompt: VoicePrompt, speed_bucket: str) -> str:
    """A deterministic file name for one (sentence, voice, speed) rendering.

    Content addressing keeps a rerun from silently replacing an earlier candidate
    with a different one under the same name.
    """

    payload = json.dumps(
        {
            "prompt_id": prompt_id,
            "text": text,
            "voice": prompt.prompt_id,
            # The prompt transcript conditions the rendering, so two prompts that
            # differ only in transcript are two different renderings and must not
            # share a name.
            "prompt_text": prompt.prompt_text,
            "speed_bucket": speed_bucket,
            "generator": GENERATOR_ID,
            "vendor_revision": VENDOR_REVISION,
            "model_revision": MODEL_REVISION,
        },
        ensure_ascii=False,
        sort_keys=True,
    )
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


class CosyVoiceReferenceGenerator:
    """Synthesises Loop A candidates through the pinned TTS interpreter."""

    def __init__(
        self,
        *,
        repository_root: str | Path,
        model_dir: str | Path,
        output_dir: str | Path,
        disclosure: str,
        interpreter: str | Path | None = None,
        worker_script: str | Path | None = None,
        vendor_dir: str | Path | None = None,
        gpu_allowed: bool = False,
        timeout_seconds: float = DEFAULT_TIMEOUT_SECONDS,
    ) -> None:
        root = Path(repository_root)
        if not root.is_absolute():
            raise ValueError("repository_root must be absolute")
        if not disclosure:
            # Synthetic exemplars cannot be built without one, so failing here keeps
            # the error next to the cause rather than deep inside the domain type.
            raise ReferenceGeneratorError("a learner-facing disclosure is required")
        self._root = root
        self._model_dir = Path(model_dir)
        self._output_dir = Path(output_dir)
        self._disclosure = disclosure
        self._interpreter = Path(
            interpreter
            if interpreter is not None
            else root / DEFAULT_INTERPRETER_RELATIVE
        )
        self._worker = Path(
            worker_script
            if worker_script is not None
            else root / DEFAULT_WORKER_RELATIVE
        )
        self._vendor = Path(
            vendor_dir if vendor_dir is not None else root / DEFAULT_VENDOR_RELATIVE
        )
        self._gpu_allowed = gpu_allowed
        self._timeout_seconds = timeout_seconds

    @property
    def generator_id(self) -> str:
        return GENERATOR_ID

    @property
    def generator_revision(self) -> str:
        return f"{VENDOR_REVISION[:12]}+{MODEL_REVISION[:12]}"

    def _environment(self) -> dict[str, str]:
        environment = {
            key: os.environ[key]
            for key in _ALLOWED_ENVIRONMENT_KEYS
            if key in os.environ
        }
        environment["PYTHONPATH"] = os.pathsep.join(
            (str(self._vendor), str(self._vendor / "third_party" / "Matcha-TTS"))
        )
        return environment

    def _run(self, request: Mapping[str, Any]) -> Mapping[str, Any]:
        if not self._interpreter.is_file():
            raise ReferenceGeneratorError("the pinned TTS interpreter is unavailable")
        if not self._worker.is_file():
            raise ReferenceGeneratorError("the TTS worker script is unavailable")
        if not self._vendor.is_dir():
            raise ReferenceGeneratorError("the vendored CosyVoice source is absent")
        try:
            completed = subprocess.run(
                [str(self._interpreter), str(self._worker)],
                input=json.dumps(request, ensure_ascii=False),
                capture_output=True,
                text=True,
                cwd=str(self._vendor),
                env=self._environment(),
                timeout=self._timeout_seconds,
                check=False,
            )
        except subprocess.TimeoutExpired as error:
            raise ReferenceGeneratorError("the TTS worker timed out") from error
        except OSError as error:
            raise ReferenceGeneratorError(
                "the TTS worker could not be started"
            ) from error

        try:
            payload = json.loads(completed.stdout)
        except (UnicodeDecodeError, json.JSONDecodeError) as error:
            raise ReferenceGeneratorError(
                "the TTS worker returned invalid JSON"
            ) from error
        if not isinstance(payload, Mapping):
            raise ReferenceGeneratorError("the TTS worker returned a non-object")
        if completed.returncode != 0 or payload.get("status") != "ok":
            detail = payload.get("error") or "worker failed"
            raise ReferenceGeneratorError(f"synthesis unavailable: {detail}")
        if payload.get("protocol_version") != WORKER_PROTOCOL_VERSION:
            raise ReferenceGeneratorError("the TTS worker protocol version differs")
        generation = payload.get("generation")
        if not isinstance(generation, Mapping):
            raise ReferenceGeneratorError("the TTS worker returned no generation")
        return generation

    def synthesise(
        self,
        *,
        prompt_id: str,
        text: str,
        voice: VoicePrompt,
        speed_bucket: str = "neutral",
    ) -> tuple[ReferenceExemplar, Path]:
        """Render one candidate and describe it as an exemplar.

        Returns the exemplar and the audio path. The path is deliberately not a field
        of the exemplar: the domain type carries a digest, and a learner-facing record
        with a filesystem path in it is how paths end up in logs.
        """

        if speed_bucket not in SPEED_BUCKETS:
            raise ReferenceGeneratorError(f"unknown speed bucket: {speed_bucket}")
        name = content_addressed_name(
            prompt_id=prompt_id, text=text, prompt=voice, speed_bucket=speed_bucket
        )
        output_path = self._output_dir / f"{name}.wav"
        generation = self._run(
            {
                "protocol_version": WORKER_PROTOCOL_VERSION,
                "text": text,
                "prompt_audio_path": str(voice.audio_path),
                "prompt_text": voice.prompt_text,
                "model_dir": str(self._model_dir),
                "output_path": str(output_path),
                "speed": SPEED_BUCKETS[speed_bucket],
                "gpu_allowed": self._gpu_allowed,
            }
        )
        if generation.get("state") != "observed":
            reason = generation.get("reason", "unknown")
            raise ReferenceGeneratorError(f"synthesis produced no audio: {reason}")

        exemplar = ReferenceExemplar(
            exemplar_id=name,
            prompt_id=prompt_id,
            generator_id=GENERATOR_ID,
            generator_revision=self.generator_revision,
            audio_sha256=sha256_file(output_path),
            duration_seconds=float(generation["duration_seconds"]),
            sample_rate=int(generation["sample_rate"]),
            speaker_axis=voice.speaker_axis,
            speed_axis=speed_bucket,
            license_spdx=voice.license_spdx,
            rights_basis=voice.rights_basis,
            synthetic=True,
            disclosure=self._disclosure,
        )
        return exemplar, output_path


